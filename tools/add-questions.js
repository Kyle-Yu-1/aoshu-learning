function qo(q){
  const keys = ['id','mod','topic','diff','type','q','opts','ans','explain','hint'];
  const p = [];
  for (const k of keys) {
    if (q[k] === undefined) continue;
    if (Array.isArray(q[k])) p.push(k + ':[' + q[k].map(qs).join(',') + ']');
    else if (typeof q[k] === 'string') p.push(k + ':' + qs(q[k]));
    else p.push(k + ':' + q[k]);
  }
  return '{' + p.join(',') + '}';
}

