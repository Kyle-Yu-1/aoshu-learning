let applied = 0;
const ops = [];
for (const item of ADD) {
  const start = txt.indexOf("id:'" + item.topic + "'");
  if (start < 0) throw new Error('topic 不存在: ' + item.topic);
  const keyAt = txt.indexOf('\n    key:[', start);
  if (keyAt < 0) throw new Error('key 定位失败: ' + item.topic);
  const secEnd = txt.lastIndexOf(']', keyAt);
  ops.push({ pos: secEnd, text: ',\n      ' + item.sec.join(',\n      ') });
  if (item.keyAdd) {
    const trapAt = txt.indexOf('\n    trap:[', keyAt);
    const keyEnd = txt.lastIndexOf(']', trapAt);
    ops.push({ pos: keyEnd, text: ",'" + item.keyAdd + "'" });
  }
  if (item.trapAdd) {
    const trapAt = txt.indexOf('\n    trap:[', keyAt);
    const thinkAt = txt.indexOf('\n    think:', trapAt);
    const trapEnd = txt.lastIndexOf(']', thinkAt);
    ops.push({ pos: trapEnd, text: ",'" + item.trapAdd + "'" });
  }
  applied++;
}
ops.sort((a, b) => b.pos - a.pos);
for (const op of ops) txt = txt.slice(0, op.pos) + op.text + txt.slice(op.pos);
fs.writeFileSync(FILE, txt, 'utf8');
console.log('知识补丁完成：' + applied + ' 个知识点');