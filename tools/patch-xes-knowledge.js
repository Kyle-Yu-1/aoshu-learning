for (const [file, topic, secs] of ADD) {
  const fp = path.join(KB, file);
  let txt = fs.readFileSync(fp, 'utf8');
  const tStart = txt.indexOf("id:'" + topic + "'");
  if (tStart < 0) throw new Error('topic 未找到: ' + file + '/' + topic);
  const trapAt = txt.indexOf("{type:'trap', title:'易错警示'", tStart);
  if (trapAt < 0) throw new Error('trap 锚点未找到: ' + file + '/' + topic);
  // 缩进对齐：trap 行首 6 空格
  const lineStart = txt.lastIndexOf('\n', trapAt);
  const indent = txt.slice(lineStart + 1, trapAt);
  const insert = secs.join(',\n') + ',\n' + indent;
  txt = txt.slice(0, trapAt) + insert + txt.slice(trapAt);
  fs.writeFileSync(fp, txt, 'utf8');
  console.log('patched', file, topic, '+' + secs.length + ' 节');
}

